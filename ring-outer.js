export function appendOuterTalents({theme,sector,route,byId,add,link,describe}) {
 const created=[];
 for(const [step,icon,entries] of PATHS[theme]){
  let previous=route[step-1];
  for(const [index,[suffix,name,position,mods,effectDescription='']] of entries.entries()){
   const id='p:outer:'+theme+':'+suffix;
   add(sector,9,{
    id,name,kind:'passive',icon,medium:index===entries.length-1,
    outerPosition:Object.freeze(position),mods:Object.freeze(mods),
    description:describe(mods,effectDescription),effectDescription
   });
   const node=byId[id];
   link(previous,node);
   created.push(node);
   previous=node;
  }
 }
 return created;
}
